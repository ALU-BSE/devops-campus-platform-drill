"""Check the infrastructure Terraform just built, and hand it off to Ansible.

Run this from your track directory after `terraform apply`:

    cd terraform/aws          # or azure, or local
    python3 ../../scripts/verify_infra.py

It does three things:

  1. Reads `terraform output -json` and checks the contract (terraform/CONTRACT.md)
     is satisfied — the same outputs, whichever track you are on.
  2. Opens TCP connections to both machines (SSH and app port on the app server,
     SSH and Postgres on the database) and tells you OPEN / REFUSED / TIMED OUT
     for each. Read that vocabulary carefully:
     they are three different results with three different fixes.
  3. Writes ansible/inventory.ini from the outputs. That file is how next
     week's Ansible playbook finds the machine you just built.
"""

import json
import socket
import subprocess
import sys
from pathlib import Path

REQUIRED_OUTPUTS = [
    "instance_public_ip",
    "instance_private_ip",
    "ssh_user",
    "app_port",
    "db_public_ip",
    "db_private_ip",
    "db_ssh_port",
]
CONNECT_TIMEOUT = 5

# The key you generated in pre-work. Ansible needs to be told which key to use;
# it will not guess, and the failure ("Permission denied (publickey)") looks like
# a server problem when it is a client one.
SSH_KEY_PATH = "~/.ssh/alu-devops"

REPO_ROOT = Path(__file__).resolve().parent.parent
INVENTORY_PATH = REPO_ROOT / "ansible" / "inventory.ini"

def read_terraform_outputs():
    """Shell out to Terraform and parse its JSON output."""
    try:
        result = subprocess.run(
            ["terraform", "output", "-json"],
            capture_output=True,
            text=True,
            check=True,
        )
    except FileNotFoundError:
        sys.exit("terraform is not on your PATH. Install it, then re-run.")
    except subprocess.CalledProcessError as exc:
        sys.exit(
            "`terraform output -json` failed. Are you inside your track directory "
            "(terraform/aws, terraform/azure or terraform/local), and have you run "
            f"`terraform apply` yet?\n\n{exc.stderr.strip()}"
        )

    raw = json.loads(result.stdout)
    return {key: entry["value"] for key, entry in raw.items()}

def check_contract(outputs):
    """The contract is the same for every track. Fail loudly if it is not met."""
    missing = [
        key
        for key in REQUIRED_OUTPUTS
        if key not in outputs or outputs[key] in (None, "")
    ]
    if missing:
        print("CONTRACT NOT MET — these outputs are missing or empty:")
        for key in missing:
            print(f"  - {key}")
        print("\nSee terraform/CONTRACT.md. Ansible cannot run without these.")
        return False

    print("Contract satisfied. Terraform produced:")
    for key in REQUIRED_OUTPUTS:
        print(f"  {key:20} = {outputs[key]}")
    return True

def probe(host, port):
    """Return OPEN, REFUSED or TIMED OUT for a single TCP port.

    The distinction is the whole point of this function:

      OPEN       something is listening and a firewall let us through.
      REFUSED    we REACHED the machine and nothing is listening on that port.
                 The network path is fine. The service is the problem.
      TIMED OUT  our packets vanished. A firewall rule dropped them silently.
                 We never reached the machine at all, so there is no point
                 debugging anything running on it. The RULE is the problem.
    """
    sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    sock.settimeout(CONNECT_TIMEOUT)
    try:
        sock.connect((host, int(port)))
        return "OPEN"
    except socket.timeout:
        return "TIMED OUT"
    except ConnectionRefusedError:
        return "REFUSED"
    except OSError as exc:
        return f"ERROR ({exc.strerror or exc})"
    finally:
        sock.close()

def write_inventory(outputs):
    """Terraform outputs -> Ansible inventory. This is the handoff to the playbook.

    Everything Ansible needs to reach the box comes from Terraform, and none of
    it is typed by hand: the address, the login user, the port, the key. Rebuild
    the infrastructure and re-run this script, and the playbook follows the box
    to its new IP without anyone editing anything.
    """
    INVENTORY_PATH.parent.mkdir(exist_ok=True)
    key = f"ansible_ssh_private_key_file={SSH_KEY_PATH}"
    user = f"ansible_user={outputs['ssh_user']}"
    INVENTORY_PATH.write_text(
        "# GENERATED by scripts/verify_infra.py from `terraform output -json`.\n"
        "# Do not hand-edit. Re-run the script after every apply.\n"
        "[campus_notifier]\n"
        f"app ansible_host={outputs['instance_public_ip']} {user} {key} "
        f"app_port={outputs['app_port']} private_ip={outputs['instance_private_ip']}\n"
        "\n"
        "[database]\n"
        f"db ansible_host={outputs['db_public_ip']} ansible_port={outputs['db_ssh_port']} "
        f"{user} {key} private_ip={outputs['db_private_ip']}\n"
    )
    print(f"\nWrote {INVENTORY_PATH.relative_to(REPO_ROOT)}.")

def main():
    outputs = read_terraform_outputs()

    if not check_contract(outputs):
        sys.exit(1)

    host = outputs["instance_public_ip"]
    app_port = outputs["app_port"]

    db_host = outputs["db_public_ip"]
    db_ssh_port = outputs["db_ssh_port"]

    print(f"\nProbing the app server at {host} ...")
    ssh_state = probe(host, 22)
    app_state = probe(host, app_port)
    print(f"  {'port 22 (SSH)':<22} : {ssh_state}")
    print(f"  {f'port {app_port} (app)':<22} : {app_state}")

    print(f"\nProbing the database at {db_host} ...")
    db_ssh_state = probe(db_host, db_ssh_port)
    db_pg_state = probe(db_host, 5432)
    print(f"  {f'port {db_ssh_port} (SSH)':<22} : {db_ssh_state}")
    print(f"  {'port 5432 (Postgres)':<22} : {db_pg_state}")

    write_inventory(outputs)

    if db_pg_state == "OPEN":
        print(
            "\nPostgres answered from your laptop. Only the app server should be "
            "able to reach it. Find the rule that lets you in."
        )
        sys.exit(1)

    for name, state in (("app server", ssh_state), ("database", db_ssh_state)):
        if state != "OPEN":
            print(f"\nSSH to the {name} is not reachable ({state}).")
    if ssh_state != "OPEN" or db_ssh_state != "OPEN":
        print(
            "Ansible cannot configure a box it cannot log into.\nBefore you change "
            "anything: say out loud what that result tells you about WHERE the "
            "problem is."
        )
        sys.exit(1)

    # An app port that is REFUSED is the expected, correct result today.
    # Terraform builds the box. It does not install or start anything on it.
    # Closing that gap is what configuration management is for — see you in session 2.
    print("\nSSH is open on both machines. They are ready to be configured.")

if __name__ == "__main__":
    main()
